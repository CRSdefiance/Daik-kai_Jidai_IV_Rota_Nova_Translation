def main():
    base = previous.parent.base
    source = base.load(previous.OUTPUT)
    assert not OUTPUT.exists() and len(source['records']) == 124
    assert list(DECISIONS) == list(range(167, previous.LAST + 1))
    for number, row in enumerate(source['records'], previous.FIRST):
        if number not in DECISIONS:
            continue
        revision, meaning, note = DECISIONS[number]
        logical = ' '.join(row['current_English'].translate(previous.WIDE_ASCII).split())
        target = revision or logical
        assert target.isascii() and '%' not in target
        assert row['id'] == f'COMMON_MESSAGE_{number}'
        row.update(english=target, source_meaning=meaning, localization_note=note, speaker='None',
            context=f'Trade-good description for {row["commodity_name"]}. The original guarded selector '
                    'maps the commodity index to this COMMON message.',
            decision='revision' if revision else 'retention',
            review=dict(source=True, context=False, localization=True, naturalness=True, formatting=False))
    assert all('decision' in row for row in source['records'])
    counts = Counter(row['decision'] for row in source['records'])
    base.save(OUTPUT, source | dict(drafted=124, editorial_decisions=dict(counts),
              predecessor=str(previous.OUTPUT), predecessor_sha256=base.digest(previous.OUTPUT)))
    print(f'All 124 descriptions have source-based prose decisions: {dict(counts)}.')


if __name__ == '__main__':
    main()
