def key(row):
    return int(row['id'].rsplit('R',1)[1]) if row['kind'] == 'ordinary-speech' else row['id']


def main():
    out = ROOT/'all328_clean_meanings_v1.json'
    assert not out.exists()
    path = ROOT/'clean_source_packet.json'
    packet = load(path)
    assert packet['source_only_not_current_English'] and len(packet['groups']) == 21
    rows = []
    for group in packet['groups']:
        number = group['block']
        assert set(MEANINGS[number]) == {key(r) for r in group['records']}
        block = bytes.fromhex(group['clean_block_hex'])
        for source in group['records']:
            row = deepcopy(source)
            raw, at = bytes.fromhex(row['source_hex']), row['source_reference']['offset']
            assert block[at:at+len(raw)] == raw and not row['covered']
            row.update(source_meaning=MEANINGS[number][key(row)], whole_exchange_context=CONTEXT[number],
                source_meaning_reviewed_from_complete_clean_exchange=True, current_English_not_consulted=True,
                independent_draft_pending=True, contextual_comparison_pending=True, new_credit=0)
            if row['kind'] == 'ordinary-speech':
                row.update(source_selector=raw[0], source_complete_preamble_hex=block[at-5:at+1].hex())
            rows.append(row)
    assert len(rows) == 328 and set(CONTEXT) == set(MEANINGS)
    save(out, dict(records=rows, source_objects=328, complete_exchanges=21,
        source_meanings_sealed_before_independent_drafts=True, no_current_story_English_read=True,
        all_five_gates_pending=True, new_credit=0, evidence={str(p):digest(p) for p in [path, Path(__file__)]}))
    print('Sealed328 clean meanings across21 complete exchanges;current English,drafts andall gates remain pending.')


if __name__ == '__main__':
    main()
