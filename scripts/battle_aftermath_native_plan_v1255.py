"""Research payload for 75 individually reviewed aftermath paragraphs.

Preserves the opaque duel component and every unselected native copy span.
No playable ROM or formatting approval is generated by this script.
"""
import struct
from pathlib import Path

from ndspy.code import MainCodeFile
from dk4tool.formats.ilnk import IlnkContainer
from dk4tool.patch.duel_special_editorial import current_entries
from dk4tool.patch.duel_editorial import owned_entries, COMPONENT, COMPONENT_SHA
from dk4tool.patch.grand_race_menu_release import sha
from dk4tool.patch.main_pool_cache_visibility import cache_plan
from dk4tool.rom.nds import NdsImage
from dk4tool.script.common_message_table import common_message_entries, DIRECTORY_OFFSET, TABLE_OFFSET
from scripts import battle_aftermath_runtime_v1253 as runtime
from scripts.battle_aftermath_layout_v1250 import IDS, PROFILE, paragraph
from scripts.verify_village_wrap_v608 import read, save

ROOT = Path('work/analysis/battle_aftermath_payload_v1255')
MANUSCRIPT = Path('translations/battle_aftermath_editorial_manuscript_v1.json')
SOURCE_COMMON = '752f8eb5a6ccf7d4e20dc0309fd1f8427f28855db01982e6b56c0d62748d682a'
SOURCE_ARM = runtime.SOURCE


def compiled(row):
    value = paragraph(row)
    if row['source_native_macros'] or any(t in row['english'] for t in ('FA','FI','FO','FU','IC')):
        raise ValueError('These 75 clean sources contain no native name/pronoun macros')
    # Compiler-owned presentation guard; translators supply one paragraph only.
    return b' '+value


def plan(common, arm, doc):
    assert sha(common) == SOURCE_COMMON and sha(arm) == SOURCE_ARM
    assert doc['translation_policy'] == 'natural-dialogue-v2' and doc['target_locale'] == 'en-US'
    assert doc['consumer_layout_profile'] == PROFILE and tuple(r['message_id'] for r in doc['records']) == IDS
    clean = NdsImage.open('work/clean.nds')
    accepted = NdsImage.open('out/raphael_natural_v2_accepted_base.nds')
    assert sha(Path('work/clean.nds').read_bytes()) == doc['source_clean_ROM_sha256']
    assert sha(Path('out/raphael_natural_v2_accepted_base.nds').read_bytes()) == '3cb827e4c52ab2086fb5a626835d72192085a958581279d3c79b0200bbf405fe'
    jp = common_message_entries(clean.read_file('/COMMON/MESFILE.DK4'),clean.read_file('/__arm9__.bin'))
    canonical = common_message_entries(accepted.read_file('/COMMON/MESFILE.DK4'),accepted.read_file('/__arm9__.bin'),clean=False)
    before = current_entries(common,arm)
    source = IlnkContainer.parse(common)
    component = COMPONENT.read_bytes()
    assert sha(component) == COMPONENT_SHA and source.blocks[21][:1484] == component+bytes(4)
    authored = {}
    for row in doc['records']:
        n = row['message_id']
        assert row['source_hex'] == jp[n].text.hex() and row['canonical_source_hex'] == canonical[n].text.hex()
        assert row['current_text_hex'] == before[n].text.hex()
        assert all(row['review'][g] for g in ('source','context','localization','naturalness'))
        assert paragraph(row).hex() == row['unwrapped_paragraph_hex']
        authored[n] = compiled(row)
    target, runtime_plan = runtime.apply(arm)
    target = bytearray(target)
    groups = {b:[r.message_id for r in before if r.block == b] for b in sorted({before[n].block for n in authored})}
    assert set(groups) == {22,23}
    rebuilt, fields, metadata_patches = list(source.blocks), [], []

    def put(at,value):
        target[at:at+len(value)] = value
        fields.append([at,len(value)])
        metadata_patches.append({'address':0x02000000+at,
            'source_hex':arm[at:at+len(value)].hex(),'target_hex':value.hex()})

    for block,numbers in groups.items():
        assert numbers == list(range(numbers[0],numbers[-1]+1))
        body = bytearray()
        for n in numbers:
            row = before[n]
            payload = source.blocks[block][row.block_offset:row.copy_end]
            assert 0 < len(payload) < 512 and payload.startswith(row.text+b'\0')
            if n in authored:
                assert not set(payload[len(row.text)+1:])-{0,32}
                payload = authored[n]+b'\0'
            put(TABLE_OFFSET+n*2,struct.pack('<H',len(body)))
            body.extend(payload)
        assert 0 < len(body) <= 8192
        rebuilt[block] = bytes(body)
        put(DIRECTORY_OFFSET+block*4,struct.pack('<HH',numbers[0],len(body)))
    c,a = IlnkContainer(rebuilt).to_bytes(),bytes(target)
    directory = sha(a[DIRECTORY_OFFSET:TABLE_OFFSET])
    after = owned_entries(c,a,directory)
    assert len(before) == len(after) == 3668
    assert all(y.text == authored.get(x.message_id,x.text) for x,y in zip(before,after,strict=True))
    assert all(rebuilt[b] == source.blocks[b] for b in range(41) if b not in groups)
    for block,numbers in groups.items():
        for n in numbers:
            if n not in authored:
                x,y = before[n],after[n]
                assert source.blocks[block][x.block_offset:x.copy_end] == rebuilt[block][y.block_offset:y.copy_end]
    restored = bytearray(a)
    patches = runtime_plan['patches']+metadata_patches
    for p in patches:
        at = p['address']-0x02000000
        value = bytes.fromhex(p['source_hex'])
        restored[at:at+len(value)] = value
    assert bytes(restored) == arm
    old,new = (MainCodeFile(v,0x02000000) for v in (arm,a))
    shape = lambda o:[(s.ramAddress,len(s.data),s.bssSize) for s in o.sections]
    assert shape(old) == shape(new) and cache_plan(arm) == cache_plan(a)
    assert all(old.sections[i].data == new.sections[i].data for i in (1,2,3,4))
    assert len(new.sections[3].data)-48 == 123040
    return c,a,{'source_COMMON_sha256':sha(common),'source_ARM9_sha256':sha(arm),
        'target_COMMON_sha256':sha(c),'target_ARM9_sha256':sha(a),'directory_sha256':directory,
        'changed_records':[f'COMMON_MESSAGE_{n}' for n in IDS],'native_IDs':list(IDS),
        'metadata_fields':fields,'patches':patches,'runtime_plan':runtime_plan,
        'repacked_native_groups':groups,'repacked_block_lengths':{str(b):len(rebuilt[b]) for b in groups},
        'all3593_unselected_texts_and_native_payloads_and39_other_blocks_exact':True,
        'opaque1484_duel_prefix_and_existing_front64_byte_helper_exact':True,
        'all_other_ARM9_bytes_restore_exact_sections_BSS_cache_ITCM_staged123040_unchanged':True,
        'font_source_pipeline_copy_registered_release_patch_and_actual_scenes_pending':True,
        'full_goal_complete':False}


def main():
    assert not ROOT.exists()
    rom = NdsImage.open('out/all_routes_combined_v1224_candidate.nds')
    doc = read(MANUSCRIPT)
    c,a,proof = plan(rom.read_file('/COMMON/MESFILE.DK4'),rom.read_file('/__arm9__.bin'),doc)
    ROOT.mkdir(parents=True)
    cp,ap = ROOT/'target_COMMON_RESEARCH_ONLY.bin',ROOT/'target_ARM9_RESEARCH_ONLY.bin'
    cp.write_bytes(c)
    ap.write_bytes(a)
    save(ROOT/'native_payload_plan.json',{**proof,'target_COMMON':str(cp),'target_ARM9':str(ap),
        'manuscript':str(MANUSCRIPT),'manuscript_sha256':sha(MANUSCRIPT.read_bytes()),
        'producer_sha256':sha(Path(__file__).read_bytes()),'no_playable_ROM_written':True})
    print('75 paragraphs packed in blocks22/23;3593 unselected texts/copies and opaque duel component preserved;native font approval pending.',flush=True)


if __name__ == '__main__':
    main()
